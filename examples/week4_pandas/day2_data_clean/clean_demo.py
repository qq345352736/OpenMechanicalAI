import pandas as pd

# 先创建一个有缺失且有异常值的数据框
data = {
    "姓名": ["张三", "李四", "王五", "赵六", "钱七", "孙八", "周九", None],
    "年龄": [25, -5, 200, 30, None, 28, 35, 40],
    "城市": ["北京", " 上海 ", "广州", "beijing", None, "深圳", "杭州", "北京"],
    "工资": [10000, 15000, 8000, -500, 20000, None, 12000, 999999],
    "入职日期": ["2022-01-15", "2021/03/20", "2023-05-01", "invalid", "2020-11-10", "2022.08.15", None, "2023-01-01"]
} 

df = pd.DataFrame(data)
print(f"原始属于:\n",df)
print(f"\n形状: ",df.shape)
# df.to_csv("original_data.csv", index=False)


'''
这份数据里几乎涵盖了所有常见问题：
问题                       出现在哪
空值                       姓名、年龄、城市、工资、入职日期
异常值（负数、离谱数字）     年龄-5、年龄200、工资-500、工资999999
格式不统一                  城市有空格、大小写混用
日期格式混乱                四种不同格式 + 一个 invalid
重复值                     后面会看到
'''

# Step 1: 先看看"脏"在哪里
print("整体信息:\n", df.info())
print("缺失值情况:\n", df.isnull().sum())
print("异常值情况:\n", df.describe())

# Step 2：处理缺失值
df=df.dropna(subset=["姓名"]) # 删除没有姓名的行,因为没有姓名就没有意义
print("处理姓名缺失值后的数据:\n", df)

df.loc[df["年龄"] < 18, "年龄"] = 18
df.loc[df["年龄"] > 60, "年龄"] = 60
df.loc[df["年龄"].isnull(), "年龄"] = df["年龄"].median()
print("处理年龄异常值后的数据:\n", df)